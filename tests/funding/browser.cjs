/* Same browser walkthrough in the public demo and application reference. */
module.exports=async function fundingWalkthrough(page,audit=async()=>{}) {
  const assert=require('node:assert/strict');
  const step=async name=>{await page.locator('[data-fw-step="'+name+'"]').click();assert(await page.locator('[data-fw-step="'+name+'"]').evaluate(n=>n===document.activeElement));};
  const actor=async name=>page.locator('[data-fw-actor]').selectOption(name);
  const message=async text=>page.waitForFunction(text=>document.querySelector('.nfw-message')?.textContent.includes(text) && document.querySelector('[data-funding-workspace]')?.getAttribute('aria-busy')!=='true',text);
  const action=async(name,text='Synthetic workspace updated')=>{await page.locator('[data-fw-action="'+name+'"]').click();await message(text);if(await page.locator('[data-fw-action="'+name+'"]').isDisabled())assert(await page.locator('.nfw-message').evaluate(n=>n===document.activeElement));};
  await page.locator('[data-funding-scenario="baseline"]').click();
  await page.locator('[data-funding-control="queue-O9"]').click();
  assert.match(await page.locator('.nfp-lower').innerText(),/Delivery constrained/);
  assert(!await page.locator('[data-funding-scenario="capacity"]').count());
  await page.locator('[data-funding-view="management"]').click();
  assert(await page.locator('[data-funding-view="management"]').evaluate(n=>n===document.activeElement));
  assert.match(await page.locator('.nfp-lower').innerText(),/Capacity gap: 1.0/);
  await page.locator('[data-funding-scenario="capacity"]').click();
  assert.match(await page.locator('.nfp-lower').innerText(),/Capacity: 5.0 required \/ 5.0 available/);
  assert.match(await page.locator('.nfp-lower').innerText(),/\$160,000/);
  await audit('management capacity option');
  await page.locator('[data-funding-view="leadership"]').click();
  assert(await page.locator('[data-funding-view="leadership"]').evaluate(n=>n===document.activeElement));
  assert.match(await page.locator('.nfp-assumption').innerText(),/add \$80,000/);
  assert.doesNotMatch(await page.locator('.nfp-lower').innerText(),/FTE quarters|Capacity gap:/);
  assert.match(await page.locator('.nfp-lower').innerText(),/\$160,000/);
  assert.match(await page.locator('.nfp-lower').innerText(),/Aggregate capacity fits/);
  await audit('leadership investment consequence');
  await page.locator('[data-funding-proposal-open]').click();
  assert(await page.locator('[data-fw-form="proposal"]').isVisible());
  await page.locator('[data-fw-back]').click();
  assert(await page.locator('[data-funding-proposal-open]').evaluate(n=>n===document.activeElement));
  await page.locator('[data-funding-workspace-open]').click();
  await step('history');await page.locator('[data-fw-reset]').click();await message('workspace reset');
  await step('proposal');
  const proposalForm=page.locator('[data-fw-form="proposal"]');
  await proposalForm.locator('[name="intent"]').fill('Improve investment decisions and protect delivery capacity.');
  await proposalForm.locator('[name="O9"]').selectOption('5');
  await proposalForm.locator('button[type="submit"]').click();await message('Reference proposal generated');
  assert.match(await page.locator('[data-fw-proposal-result]').innerText(),/INCOMPLETE/);
  assert.match(await page.locator('[data-fw-proposal-result]').innerText(),/10 FTE quarters/);
  await audit('leadership reference proposal');
  await actor('viewer');assert(await page.locator('[data-fw-import]').isDisabled());await actor('leader');
  await proposalForm.locator('[name="envelope"]').fill('1.00');assert(!await page.locator('[data-fw-import]').count());
  await proposalForm.locator('button[type="submit"]').click();await message('Reference proposal generated');
  assert(await page.locator('[data-fw-import]').isDisabled());
  await proposalForm.locator('[name="envelope"]').fill('1000000.00');
  await proposalForm.locator('button[type="submit"]').click();await message('Reference proposal generated');
  await page.locator('[data-fw-discard]').click();await message('Proposal discarded');
  await proposalForm.locator('button[type="submit"]').click();await message('Reference proposal generated');
  await page.locator('[data-fw-import]').click();await message('Reference proposal added');
  assert.match(await page.locator('.nfw-context').innerText(),/Draft revision 2 · DRAFT · Effective revision NONE/);
  await step('history');assert.match(await page.locator('.nfw-panel:visible').innerText(),/INVESTMENT_PROPOSAL_IMPORTED/);
  await page.locator('[data-fw-reset]').click();await message('workspace reset');
  const envelope=page.locator('[data-fw-form="envelope"]');
  await envelope.locator('[name="envelope"]').fill('1000000.00');
  await envelope.locator('[name="O9"]').fill('450000.00');
  await envelope.locator('[name="O10"]').fill('300000.00');
  await envelope.locator('[name="O11"]').fill('150000.00');
  await envelope.locator('button[type="submit"]').click();await message('Synthetic workspace updated');
  await actor('manager');await step('ledger');
  const epic=page.locator('[data-fw-form="epic"]');
  await epic.locator('[name="remaining"]').fill('1.001');
  await epic.locator('button[type="submit"]').click();await message('at most two decimal');
  assert.equal(await epic.locator('[name="remaining"]').inputValue(),'1.001');
  await epic.locator('[name="remaining"]').fill('180000.00');
  await epic.locator('button[type="submit"]').click();await message('Synthetic workspace updated');
  assert.match(await page.locator('.nfw-panel:visible').innerText(),/O9 80% \/ O10 20%/);
  await page.locator('[data-fw-epic]').selectOption('NEW');
  await epic.locator('[name="epicId"]').fill('EP-DEMO-TRAINING');
  await epic.locator('[name="title"]').fill('Fictional enablement');
  await epic.locator('[name="allocation"]').fill('1000.00');
  await epic.locator('[name="remaining"]').fill('1234.56');
  await epic.locator('[name="capacity"]').fill('0.50');
  await epic.locator('[name="basis"]').fill('Synthetic training estimate; actuals have not been supplied.');
  await epic.locator('button[type="submit"]').click();await message('Synthetic workspace updated');
  await page.waitForFunction(()=>document.querySelector('[data-fw-epic]')?.value==='EP-DEMO-TRAINING');
  assert.match(await page.locator('.nfw-panel:visible').innerText(),/3 of 5 Epics/);
  await audit('funding entry and shared Epic ledger');
  await step('review');await page.locator('[data-fw-reason]').fill('Synthetic exercise: review the exact estimates and missing financial coverage.');
  await action('submit','Exact synthetic package submitted');
  await actor('leader');assert(await page.locator('[data-fw-action="approve"]').isDisabled());
  await actor('reviewer');assert(!(await page.locator('[data-fw-action="approve"]').isDisabled()));
  await audit('funding submitted review');
  await action('approve','SIMULATED APPROVED');
  const activeRevision=(await page.locator('.nfw-context').innerText()).match(/Effective revision (\d+)/)[1];
  await step('history');assert.match(await page.locator('.nfw-panel:visible').innerText(),/APPROVED · DEC-1/);
  await audit('funding approved history');
  await actor('manager');await step('review');await action('revise');
  assert.match(await page.locator('.nfw-context').innerText(),new RegExp('Effective revision '+activeRevision));
  await action('submit','Exact synthetic package submitted');
  await actor('finance');await step('reconcile');await action('finance');
  await step('review');assert(await page.locator('[data-fw-action="approve"]').isDisabled());
  assert.match(await page.locator('.nfw-context').innerText(),new RegExp('Effective revision '+activeRevision));
  await step('history');assert.match(await page.locator('.nfw-panel:visible').innerText(),/REVIEW_INVALIDATED/);
  await actor('manager');await step('review');await action('submit','Exact synthetic package submitted');
  await actor('reviewer');await action('reject','SIMULATED REJECTED');
  assert.match(await page.locator('.nfw-context').innerText(),new RegExp('Effective revision '+activeRevision));
  await actor('finance');await step('reconcile');await action('unmatched');
  assert.match(await page.locator('.nfw-panel:visible').innerText(),/Unmatched suspense: \$123\.45/);
  await page.locator('[data-fw-form="map"] button[type="submit"]').click();await message('Synthetic workspace updated');
  assert.match(await page.locator('.nfw-panel:visible').innerText(),/No unmatched observations remain/);
  await actor('manager');await step('review');await action('revise');await action('submit','Exact synthetic package submitted');
  await actor('reviewer');await action('approve','SIMULATED APPROVED');
  await step('history');const history=await page.locator('.nfw-panel:visible').innerText();
  assert.match(history,/APPROVED · DEC-1/);assert.match(history,/REJECTED · DEC-2/);assert.match(history,/APPROVED · DEC-3/);
  assert.match(history,/SOURCE_MAP/);assert.match(history,/No durable audit store|no durable audit store/);
  await audit('funding revised decision and reconciliation history');
  await page.locator('[data-fw-back]').click();assert(await page.locator('.nfp').isVisible());
  await page.locator('[data-funding-workspace-open]').click();await step('history');assert.match(await page.locator('.nfw-panel:visible').innerText(),/APPROVED · DEC-3/);
  await page.locator('[data-fw-back]').click();
};
